#!/usr/bin/env python3
"""
Export the panel's lo-fi assets for the device (javascript/midigpt_panel.js):

  media/panel/midigpt_*.png        page backgrounds and part sprites (2x), Carbon theme
  javascript/midigpt_panel_spec.js  the layout (frontend_assets.py page specs, sprite
                                offsets) and the theme's UI colours

The same renderer and layout as the browser prototype (tools/frontend_assets.py).

  python3 tools/export_panel_assets.py [theme] [--spec-only]

--spec-only rewrites only the layout (midigpt_panel_spec.js) and leaves the PNGs alone: the installed ones are
Blender renders (see CLAUDE.md), which this script would replace with its lo-fi shading.
"""

import json
import os
import shutil
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import frontend_assets as FA  # noqa: E402
from PIL import Image  # noqa: E402
import render_ui as R  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MEDIA = os.path.join(ROOT, "media", "panel")
SPEC_JS = os.path.join(ROOT, "javascript", "midigpt_panel_spec.js")
PREFIX = "midigpt_"
DIMS = {"knob": (55,), "thumb": (50,), "key": (28, 50, 62)}   # alpha %, as in midigpt_panel.js DIMS


def main():
    args = [a for a in sys.argv[1:] if a != "--spec-only"]
    spec_only = len(args) < len(sys.argv) - 1
    theme = args[0] if args else "carbon"
    tmp = tempfile.mkdtemp()
    meta = FA.export_theme(theme, tmp)
    if spec_only:
        shutil.rmtree(tmp)
        write_spec(theme, meta)
        return
    os.makedirs(MEDIA, exist_ok=True)
    for f in os.listdir(MEDIA):
        if f.startswith(PREFIX):
            os.remove(os.path.join(MEDIA, f))
    for f in sorted(os.listdir(tmp)):
        shutil.copy(os.path.join(tmp, f), os.path.join(MEDIA, PREFIX + f))
        if not f.startswith("bg_"):   # pre-dimmed copies for disabled parts (midigpt_panel.js DIMS)
            im = Image.open(os.path.join(tmp, f)).convert("RGBA")
            for a in DIMS[f.split("_")[0]]:
                d = im.copy()
                d.putalpha(d.getchannel("A").point(lambda v, a=a: int(v * a / 100 + 0.5)))
                d.save(os.path.join(MEDIA, PREFIX + f.replace(".png", "_a%d.png" % a)), optimize=True)
    shutil.rmtree(tmp)
    write_spec(theme, meta)


def write_spec(theme, meta):
    spec = dict(top_keys=FA.TOP_KEYS, screen=FA.SCREEN, output=FA.OUTPUT, extras=FA.EXTRAS, pages=FA.PAGES, sprites=meta)
    with open(SPEC_JS, "w") as f:
        f.write("// Generated by tools/export_panel_assets.py -- do not edit.\n")
        f.write("// include()d by midigpt_panel.js (require() would keep a stale copy cached).\n")
        f.write("var MidigptPanelSpec = { SPEC: " + json.dumps(spec) + ",\n  THEME: " + json.dumps(FA.THEMES[theme]["ui"]) + " };\n")
    print("theme", theme, "->", os.path.relpath(MEDIA, ROOT), "and", os.path.relpath(SPEC_JS, ROOT))


if __name__ == "__main__":
    main()
